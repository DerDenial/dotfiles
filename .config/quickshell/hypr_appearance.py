#!/usr/bin/env python3
"""Theme translucent window frames, fallback canvas and native dialogs."""
import importlib.util
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile


def palette_color(palette, role):
    color = palette[role]
    if not isinstance(color, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", color):
        raise ValueError("Invalid Hyprland appearance color: " + role)
    return color[1:].lower()


def apply_hypr_appearance(palette, config, write):
    roles = {"background": "bgDim", "base": "surface", "alternate_base": "surfaceAlt",
             "text": "text", "bright_text": "textBright", "link_text": "accent",
             "accent": "accent", "accent_secondary": "aqua"}
    toolkit = "# Generated by the Quickshell theme switcher.\n"
    toolkit += "".join(name + " = 0xff" + palette_color(palette, role) + "\n"
                       for name, role in roles.items())
    toolkit += """font_family = Inter
font_family_monospace = JetBrainsMono Nerd Font
h1_size = 28
h2_size = 16
h3_size = 13
font_size = 12
small_font_size = 10
rounding_large = 24
rounding_small = 12
"""
    write(config / "hypr/hyprtoolkit.conf", toolkit)
    # Translucent frames identify the focused window without a bright outline.
    accent = palette_color(palette, "accent")
    active_border = "rgba(" + accent + "70)"
    inactive_border = "rgba(" + palette_color(palette, "border") + "55)"
    background = "rgb(" + palette_color(palette, "bgDim") + ")"
    write(config / "hypr/modules/theme-colors.lua", (
        "-- Generated by Quickshell theme switcher.\nreturn {\n"
        f'    active_border = "{active_border}",\n'
        f'    inactive_border = "{inactive_border}",\n'
        f'    background_color = "{background}",\n'
        "}\n"
    ))
    if shutil.which("hyprctl"):
        expression = ("hl.config({ general = { col = { "
                      f'active_border = "{active_border}", inactive_border = "{inactive_border}"'
                      " } }, decoration = { shadow = { enabled = false } }, misc = { "
                      f'background_color = "{background}", disable_hyprland_logo = true, '
                      'disable_splash_rendering = true, font_family = "Inter"'
                      " } })")
        try:
            subprocess.run(["hyprctl", "eval", expression], check=False, timeout=8)
        except (OSError, subprocess.TimeoutExpired) as error:
            print("Hyprland appearance update failed:", error, file=sys.stderr)


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix="." + path.name + "-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w") as output:
            output.write(content)
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


if __name__ == "__main__":
    if sys.argv[1:] != ["--current"]:
        raise SystemExit("Use hypr_appearance.py --current")
    home = Path.home()
    source = home / ".config/quickshell/sync-sddm.py"
    spec = importlib.util.spec_from_file_location("quickshell_saved_appearance", source)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    _, palette, _ = module.current_appearance()
    apply_hypr_appearance(palette, Path(os.environ.get("XDG_CONFIG_HOME", home / ".config")), atomic_write)
